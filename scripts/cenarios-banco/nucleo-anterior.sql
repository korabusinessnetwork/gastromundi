-- Núcleo que existia no banco antes das migrations (gerado de supabase/schema.sql pelo
-- script dos cenários): as tabelas, sem tenant_id, que as migrations acrescentam.

CREATE TABLE IF NOT EXISTS public.users (
  id        bigint  PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name      text    NOT NULL,
  username  text    NOT NULL UNIQUE,
  role      text    NOT NULL,
  active    boolean NOT NULL DEFAULT true,
  auth_id   uuid    UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.products (
  id                    bigint  PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name                  text    NOT NULL,
  price                 numeric NOT NULL,
  category              text    NOT NULL,
  emoji                 text,
  active                boolean NOT NULL DEFAULT true,
  unidades_compra       jsonb   NOT NULL DEFAULT '[]',
  unidade_estoque       text    NOT NULL DEFAULT 'un',
  unidade_consumo       text,
  fator_consumo_estoque numeric DEFAULT 1,
  produzivel            boolean NOT NULL DEFAULT true, -- F015, 20260721_produtos_produzivel.sql
  validade_dias         integer,                       -- C1, 20260731_produtos_validade.sql
  proxima_validade      date,                          -- C1, 20260731_produtos_validade.sql
  codigo_barras         text                          -- 20260745_produtos_codigo_barras.sql
);

CREATE TABLE IF NOT EXISTS public.pending (
  id         text  PRIMARY KEY,
  comanda    text,
  items      jsonb NOT NULL DEFAULT '[]',
  status     text  NOT NULL DEFAULT 'open',
  note       text,
  total      numeric,
  garcom     text,
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  mesa       text,
  apelido    text
);

CREATE TABLE IF NOT EXISTS public.sales (
  id        text  PRIMARY KEY,
  data      jsonb NOT NULL DEFAULT '{}',
  at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.config (
  key       text  PRIMARY KEY,
  value     jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS public.fechamentos (
  id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  data       jsonb  NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.locais_impressao (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nome       text NOT NULL,
  descricao  text,
  ativo      boolean DEFAULT true,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.categorias_roteamento (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  categoria          text NOT NULL,
  local_impressao_id uuid REFERENCES public.locais_impressao(id) ON DELETE SET NULL,
  updated_at         timestamptz DEFAULT now()
);
